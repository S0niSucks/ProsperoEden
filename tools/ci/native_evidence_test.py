class NativeEvidenceTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix='native-evidence-test-')
        self.base = Path(self.tmp.name)
        self.app = self.base / 'approved' / 'app'
        self.app.mkdir(parents=True)
        self.destination = self.base / 'evidence'
        self.original_cwd = Path.cwd()
        os.chdir(self.app)
        self.addCleanup(os.chdir, self.original_cwd)
        self.addCleanup(self.tmp.cleanup)
        self.initialize()

    def initialize(self, roots=None):
        ne.initialize(str(self.destination), roots or ['app=' + str(self.app)])
        self.evidence = ne.Evidence(str(self.destination))

    def file(self, name, data=b'synthetic bytes\n', mode=0o644):
        path = self.app / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        path.chmod(mode)
        return str(path)

    def producer(self, body='printf produced > "$1"\n'):
        return self.file('tools/mock-producer', ('#!/bin/bash\n' + body).encode(), 0o755)

    def capture(self, paths, **kw):
        return ne.record(self.evidence, 'test-phase', paths, [], [], **kw)

    def phases(self):
        return sorted((self.destination / 'events').iterdir())

    def after(self):
        return ne.read_json(self.phases()[-1] / 'after.json')

    def verify(self):
        with contextlib.redirect_stdout(io.StringIO()) as output:
            ne.check(str(self.destination))
        return json.loads(output.getvalue())

    def test_regular_bytes_mode_and_pending(self):
        path = self.file('source.c', b'\r\nunaltered\x00\xff\n', 0o751)
        self.capture([path])
        row = self.after()['inputs'][0]
        self.assertEqual(row['mode'], 0o751)
        self.assertEqual(row['sha256'], hashlib.sha256(Path(path).read_bytes()).hexdigest())
        blob = self.phases()[0] / row['blob']
        self.assertEqual(blob.read_bytes(), Path(path).read_bytes())
        self.assertEqual(stat.S_IMODE(blob.stat().st_mode), 0o600)
        self.assertEqual(self.verify()['qualification'], 'PENDING')

    def test_init_refuses_existing_empty_or_nonempty_destination(self):
        old = (self.destination / 'run.json').read_bytes()
        with self.assertRaises(FileExistsError):
            self.initialize()
        self.assertEqual((self.destination / 'run.json').read_bytes(), old)
        empty = self.base / 'empty'
        empty.mkdir()
        with self.assertRaises(FileExistsError):
            ne.initialize(str(empty), ['app=' + str(self.app)])

    def test_append_only_repeated_phase(self):
        path = self.file('one.c')
        self.capture([path])
        first = {str(p.relative_to(self.destination)): p.read_bytes()
                 for p in self.phases()[0].rglob('*') if p.is_file()}
        self.capture([path])
        self.assertEqual(self.verify()['events'], 2)
        for relative, data in first.items():
            self.assertEqual((self.destination / relative).read_bytes(), data)

    def test_phase_files_are_exact_phase_scoped_snapshots(self):
        selected = self.file('generated.c', b'actual generated bytes')
        unused = self.file('not-for-this-phase.c', b'must not capture')
