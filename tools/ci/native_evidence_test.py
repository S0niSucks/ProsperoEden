        ne.initialize(str(destination), ['app=' + str(self.app)],
                      ['test-phase=' + selected, 'other-phase=' + unused])
        self.destination = destination
        self.evidence = ne.Evidence(str(destination))
        self.capture([])
        self.assertEqual([r['path'] for r in self.after()['inputs']], ['generated.c'])
        self.assertEqual(self.verify()['unobserved_selection_phases'], ['other-phase'])

